import type { Metadata } from "next";
import { notFound } from "next/navigation";
import PostView from "@/components/blog/PostView";
import { nepaliPosts, posts as blogData } from "@/lib/blog";
import { postMetadata } from "@/lib/post-metadata";

/**
 * /ne/blog/[slug] — the Nepali journal.
 *
 * The three Nepali articles were at /blog/<slug>, on the same shelf as the
 * English ones with nothing in the URL to say which language they were in.
 * /ne/ is the locale prefix the rest of the site adopts if the Nepali
 * experiment works (docs/i18n-plan.md); English stays un-prefixed, so no
 * existing English URL had to move. The old Nepali URLs 301 here.
 *
 * Same <PostView> and the same metadata helper as the English route — the
 * hreflang pair is reciprocal because both sides are generated by one function
 * rather than written twice.
 */

interface Props {
  params: Promise<{ slug: string }>;
}

export function generateStaticParams() {
  return nepaliPosts().map((post) => ({ slug: post.slug }));
}

/** As on the English route: a real 404 for an unknown slug, not a soft one. */
export const dynamicParams = false;

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { slug } = await params;
  const post = blogData.find((p) => p.slug === slug && p.lang === "ne");
  if (!post) return { title: "Post Not Found", robots: { index: false } };
  return postMetadata(post);
}

export default async function NepaliBlogPostPage({ params }: Props) {
  const { slug } = await params;
  const post = blogData.find((p) => p.slug === slug && p.lang === "ne");
  if (!post) notFound();
  return <PostView post={post} />;
}
